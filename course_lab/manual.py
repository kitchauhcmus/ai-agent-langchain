"""MANUAL TOOL CALLING. Simulated planner, explicit schema, validation, execution.

The rule-based parser is NOT an LLM; it merely demonstrates the same plumbing.
"""

import json
import re
from .tools import StudyTools

# This registry is deliberately explicit, not eval() or arbitrary code execution.
TOOL_SCHEMAS = {
    "calculator": {
        "description": "Perform safe arithmetic",
        "required": {"a": "number", "b": "number", "operation": "string"},
        "optional": {},
    },
    "average_score": {"description": "Average grade (SQL)", "required": {}, "optional": {}},
    "top_students": {
        "description": "Highest-scoring students (SQL)",
        "required": {}, "optional": {"limit": "integer"},
    },
    "list_grades": {"description": "All synthetic grades (SQL)", "required": {}, "optional": {}},
    "plot_scores": {"description": "Create an SVG chart", "required": {}, "optional": {}},
    "search_notes": {
        "description": "Retrieve a note by keyword",
        "required": {"topic": "string"}, "optional": {},
    },
}


def _type_matches(value, expected):
    if expected == "number":
        return type(value) in (int, float)
    if expected == "integer":
        return type(value) is int
    if expected == "string":
        return isinstance(value, str)
    return False


def validate_tool_call(call: dict) -> None:
    """Reject missing/extra/wrong-typed tool args before execution."""
    if not isinstance(call, dict) or set(call) != {"name", "arguments"}:
        raise ValueError("Tool request must have name and arguments")
    name, args = call["name"], call["arguments"]
    if name not in TOOL_SCHEMAS:
        raise ValueError(f"Unknown tool: {name}")
    if not isinstance(args, dict):
        raise ValueError("arguments must be a JSON object")
    schema = TOOL_SCHEMAS[name]
    required, optional = schema["required"], schema["optional"]
    for key, expected in required.items():
        if key not in args or not _type_matches(args[key], expected):
            raise ValueError(f"Missing/invalid required argument: {key} ({expected})")
    allowed = {**required, **optional}
    for key, value in args.items():
        if key not in allowed or not _type_matches(value, allowed.get(key)):
            raise ValueError(f"Unknown/invalid argument: {key}")


def execute_tool_call(call: dict, tools: StudyTools) -> dict:
    validate_tool_call(call)
    function = getattr(tools, call["name"])
    return function(**call["arguments"])


def parse_offline_command(command: str) -> dict | None:
    """Small deterministic router, unlike an LLM which understands free text."""
    text = command.strip()
    normalized = text.lower()
    if normalized.startswith("calc "):
        pattern = r"^calc\s+(-?\d+(?:\.\d+)?)\s*([+*/-])\s*(-?\d+(?:\.\d+)?)$"
        found = re.match(pattern, text, flags=re.IGNORECASE)
        if not found:
            raise ValueError("Use: calc 12 * 5")
        a, op, b = found.groups()
        operations = {"+": "add", "-": "subtract", "*": "multiply", "/": "divide"}
        return {"name": "calculator", "arguments": {"a": float(a), "b": float(b), "operation": operations[op]}}
    if normalized in ("avg", "average", "average score"):
        return {"name": "average_score", "arguments": {}}
    if normalized.startswith("top"):
        found = re.fullmatch(r"top(?:\s+(\d+))?", normalized)
        if not found:
            raise ValueError("Use: top 3")
        return {"name": "top_students", "arguments": {"limit": int(found[1] or "3")}}
    if normalized in ("grades", "students", "list"):
        return {"name": "list_grades", "arguments": {}}
    if normalized in ("chart", "plot", "visualize"):
        return {"name": "plot_scores", "arguments": {}}
    if normalized.startswith("notes "):
        return {"name": "search_notes", "arguments": {"topic": text[6:].strip()}}
    return None


def manual_demo(tools: StudyTools, command: str) -> dict | None:
    call = parse_offline_command(command)
    if call is None:
        return None
    print("1. Structured tool call (not generated by an LLM in offline mode):")
    print(json.dumps(call, indent=2))
    result = execute_tool_call(call, tools)
    print("2. Python executed the tool and got:")
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return result
